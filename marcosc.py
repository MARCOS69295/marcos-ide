from __future__ import annotations

import argparse
import importlib.util
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from marcos_engine import MarcosCompiler, MarcosRuntime, load_bytecode, save_bytecode


def safe_app_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]", "_", name).strip("_")
    if not cleaned:
        raise ValueError("nome inválido para o executável")
    return cleaned[:80]


def build_windows_exe(source_path: Path, output_dir: Path, name: str | None = None,
                      keep_marc: bool = False, pause: bool = True) -> Path:
    # Empacota VM + bytecode em um executável de console Windows.
    if sys.platform != "win32":
        raise RuntimeError(
            "A geração de .exe Windows precisa ser executada no Windows. "
            "Este ambiente não é Windows e não pode produzir um executável Windows."
        )
    if importlib.util.find_spec("PyInstaller") is None:
        raise RuntimeError(
            "PyInstaller não está instalado. Execute: "
            "python -m pip install -r requirements-build.txt"
        )

    source_path = source_path.resolve()
    if not source_path.is_file():
        raise FileNotFoundError(f"arquivo fonte não encontrado: {source_path}")
    if source_path.suffix.lower() != ".mar":
        raise ValueError("o arquivo de entrada deve ter extensão .mar")

    output_dir = output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    app_name = safe_app_name(name or source_path.stem)

    code = MarcosCompiler().compile_source(
        source_path.read_text(encoding="utf-8"),
        name=source_path.name,
    )

    temp_root = Path(tempfile.mkdtemp(prefix="marcos_exe_build_"))
    try:
        marc_path = temp_root / "programa.marc"
        save_bytecode(code, marc_path)

        launcher_path = temp_root / "marcos_launcher.py"
        launcher_lines = [
            "# Generated by MARCOS IDE 7.0",
            "from pathlib import Path",
            "import sys",
            "from marcos_engine import MarcosVM, load_bytecode",
            "",
            'root = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent))',
            'program = load_bytecode(root / "programa.marc")',
            "vm = MarcosVM()",
            "",
            "try:",
            "    for line in vm.execute(program):",
            "        print(line)",
            "except Exception as error:",
            '    print(f"Erro na execução MARCOS: {type(error).__name__}: {error}")',
            "    raise SystemExit(1)",
        ]
        if pause:
            launcher_lines.extend(["", "input('Pressione ENTER para fechar...')"])
        launcher_path.write_text("\n".join(launcher_lines) + "\n", encoding="utf-8")

        work_dir = temp_root / "work"
        spec_dir = temp_root / "spec"
        command = [
            sys.executable, "-m", "PyInstaller",
            "--noconfirm", "--clean", "--onefile", "--console",
            "--name", app_name,
            "--distpath", str(output_dir),
            "--workpath", str(work_dir),
            "--specpath", str(spec_dir),
            "--paths", str(Path(__file__).resolve().parent),
            "--hidden-import", "marcos_engine",
            "--add-data", f"{marc_path};.",
            str(launcher_path),
        ]
        completed = subprocess.run(command, cwd=temp_root, check=False)
        if completed.returncode != 0:
            raise RuntimeError(
                f"PyInstaller terminou com código {completed.returncode}. "
                "Consulte as mensagens do terminal."
            )

        exe_path = output_dir / f"{app_name}.exe"
        if not exe_path.is_file():
            raise RuntimeError("PyInstaller terminou, mas o EXE não foi encontrado.")
        if keep_marc:
            shutil.copy2(marc_path, output_dir / f"{app_name}.marc")
        return exe_path
    finally:
        shutil.rmtree(temp_root, ignore_errors=True)


def main():
    parser = argparse.ArgumentParser(
        prog="marcos",
        description="Compilador e ferramentas da Linguagem MARCOS 7.0",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    compile_cmd = sub.add_parser("compile", help="compila .mar para .marc")
    compile_cmd.add_argument("source")
    compile_cmd.add_argument("-o", "--output")

    run_cmd = sub.add_parser("run", help="executa arquivo .mar ou .marc")
    run_cmd.add_argument("file")

    dis_cmd = sub.add_parser("disasm", help="mostra o bytecode de um .marc")
    dis_cmd.add_argument("file")

    build_cmd = sub.add_parser("build", help="gera executável Windows .exe")
    build_cmd.add_argument("source", help="arquivo fonte .mar")
    build_cmd.add_argument("-o", "--output-dir", default="dist")
    build_cmd.add_argument("--name", help="nome do arquivo .exe")
    build_cmd.add_argument("--keep-marc", action="store_true",
                           help="mantém também o bytecode .marc na pasta de saída")
    build_cmd.add_argument("--no-pause", action="store_true",
                           help="não aguarda ENTER ao terminar o programa")

    args = parser.parse_args()

    if args.command == "compile":
        source_path = Path(args.source)
        output = Path(args.output) if args.output else source_path.with_suffix(".marc")
        code = MarcosCompiler().compile_source(
            source_path.read_text(encoding="utf-8"), name=source_path.name
        )
        save_bytecode(code, output)
        print(f"Compilado: {output}")
    elif args.command == "run":
        file_path = Path(args.file)
        runtime = MarcosRuntime()
        if file_path.suffix.lower() == ".marc":
            results = runtime.run_file(file_path)
        else:
            results = runtime.run(file_path.read_text(encoding="utf-8"))
        for line in results:
            print(line)
    elif args.command == "disasm":
        code = load_bytecode(args.file)
        print(MarcosCompiler.disassemble(code))
    elif args.command == "build":
        exe = build_windows_exe(
            Path(args.source),
            Path(args.output_dir),
            name=args.name,
            keep_marc=args.keep_marc,
            pause=not args.no_pause,
        )
        print(f"Executável gerado: {exe}")


if __name__ == "__main__":
    main()
